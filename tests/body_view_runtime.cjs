'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const page=fs.readFileSync(0,'utf8'),elements=new Map();let draws=0;
const graphics=new Proxy({}, {get:(_,key)=>key==='fillRect'?()=>draws++:()=>{}});
for(const m of page.matchAll(/id="([^"]+)"/g))elements.set(m[1],{textContent:'',hidden:false,clientWidth:900,clientHeight:600,getContext:()=>graphics,setAttribute(name,value){this[name]=value;}});
const document={getElementById:id=>elements.get(id),querySelectorAll:()=>[]};
const preferences=new Map(),localStorage={getItem:key=>preferences.get(key),setItem:(key,value)=>preferences.set(key,value)};
const listeners={},context=vm.createContext({document,window:{addEventListener(name,fn){listeners[name]=fn;}},devicePixelRatio:1,localStorage});
vm.runInContext(page.match(/<script>([\s\S]*?)<\/script>/)[1],context,{timeout:5000});
assert.ok(draws>100,'body preview must finish drawing its point cloud');
assert.match(elements.get('status').textContent,/坐标|对齐/);
assert.match(elements.get('quality').textContent,/RMS/);
assert.equal(elements.get('coordinateInfo').hidden,false);
vm.runInContext('yaw=.8;pitch=.4;zoom=2',context);
const before=draws;elements.get('toggleInfo').onclick();
assert.equal(elements.get('coordinateInfo').hidden,true);
assert.equal(elements.get('toggleInfo')['aria-expanded'],'false');
assert.equal(preferences.get('pointcloud-body-info-hidden'),'1');
assert.ok(draws>before,'collapse must redraw at the new canvas size');
assert.equal(vm.runInContext('yaw===.8&&pitch===.4&&zoom===2',context),true);
elements.get('toggleInfo').onclick();
assert.equal(elements.get('coordinateInfo').hidden,false);
assert.equal(elements.get('toggleInfo')['aria-expanded'],'true');
listeners.storage({key:'pointcloud-body-info-hidden',newValue:'1'});
assert.equal(elements.get('coordinateInfo').hidden,true,'preloaded sibling viewers must follow the same preference');
listeners.storage({key:'pointcloud-body-info-hidden',newValue:'0'});
assert.equal(elements.get('coordinateInfo').hidden,false);
process.stdout.write('body viewer executed');
